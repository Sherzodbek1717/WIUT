"""Run the test suite and write docs/test-results.md from the real results.

Usage (from the smart-dispatch folder, virtual environment active):
    python scripts/test_report.py
"""

import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINE = re.compile(r"^(test_\w+) \(tests\.(\w+)\.(\w+)\.\w+\) \.\.\. (ok|FAIL|ERROR)")

# Which requirement each group of tests provides evidence for.
AREAS = {
    "test_requirements": "FR1–FR10 (PID functional requirements)",
    "test_engine": "FR6 Decision engine (unit tests)",
    "test_dispatch": "FR1/FR4/FR5 Workflow and role security",
    "test_telegram_bot": "Telegram bot (PID should-have)",
    "test_loadboard": "Load board, truck search, REST API",
    "test_copilot": "AI Co-Pilot: email, calls, broker directory",
}


def main():
    run = subprocess.run(
        [sys.executable, "manage.py", "test", "tests", "-v", "2"],
        cwd=ROOT, capture_output=True, text=True,
    )
    output = run.stdout + run.stderr
    rows = [LINE.match(line).groups() for line in output.splitlines() if LINE.match(line)]
    total = re.search(r"Ran (\d+) tests", output)
    passed = sum(1 for r in rows if r[3] == "ok")

    lines = [
        "# Test results",
        "",
        f"Generated by `scripts/test_report.py` on {datetime.now():%d %B %Y %H:%M} from a real run of the automated test suite.",
        "",
        f"**{passed} of {total.group(1) if total else len(rows)} tests passed.**",
        "",
    ]
    for module, area in AREAS.items():
        # Natural order, so FR2 comes before FR10.
        group = sorted((r for r in rows if r[1] == module),
                       key=lambda r: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", r[0])])
        if not group:
            continue
        lines += [f"## {area}", "", "| # | Test | Group | Result |", "|---|---|---|---|"]
        for i, (name, _, cls, result) in enumerate(group, 1):
            label = re.sub(r"^Fr(\d+)", r"FR\1", name.removeprefix("test_").replace("_", " ").capitalize())
            lines.append(f"| {i} | {label} | {cls} | {'Pass' if result == 'ok' else result} |")
        lines.append("")
    (ROOT / "docs" / "test-results.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{passed}/{len(rows)} passed. Wrote docs/test-results.md")
    return 0 if run.returncode == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
